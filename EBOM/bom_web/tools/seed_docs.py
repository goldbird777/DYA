def seed():
    init_db()
    for kind, rows in (('usage', USAGE), ('rfp', RFP)):
        exist = {p['title'] for p in get_doc_posts(kind)}
        n = 0
        for cat, order, title, body in rows:
            if title in exist:
                continue
            add_doc_post(kind, cat, title, body.strip(), 'admin', order)
            n += 1
        print(f'{kind}: {n}건 추가 (기존 {len(exist)}건)')


if __name__ == '__main__':
    seed()
